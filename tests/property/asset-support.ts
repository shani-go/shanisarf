export const sha256Hex = (bytes: Uint8Array): string => createHash('sha256').update(bytes).digest('hex');

/** A Source_Record describing `bytes`. */
export function recordFor(bytes: Uint8Array): SourceRecord {
  return {
    id: 'property-db',
    name: 'A generated database',
    version: '0.0',
    source: 'https://example.invalid/property.db',
    sourceSha256: sha256Hex(bytes),
    sourceBytes: bytes.length,
    license: { id: 'CC0-1.0', url: 'https://creativecommons.org/publicdomain/zero/1.0/' },
    credits: 'Generated by a property test.',
    disclaimer: 'No warranty.',
    citation: 'None.',
  };
}

/** `text` compiled in memory. */
export async function compileText(text: string, level?: number): Promise<CompiledAsset> {
  const bytes = new TextEncoder().encode(text);
  return compileDatabase(bytes, recordFor(bytes), level === undefined ? {} : { level });
}

/** A copy of an Asset's bytes that a test may change. */
export function assetCopy(asset: AssetBytes): AssetBytes {
  return {
    manifest: asset.manifest.slice(),
    shards: Object.fromEntries(Object.entries(asset.shards).map(([path, b]) => [path, b.slice()])),
  };
}

/** The two entries' `openAsset`: the stream inflate and `node:zlib`. */
export const OPENERS: Readonly<Record<'stream' | 'zlib', (b: AssetBytes, o?: OpenOptions) => Promise<MorphologyDb>>> = {
  stream: (b, o) => openAssetWith(inflate, b, o),
  zlib: (b, o) => openAssetWith(inflateNode, b, o),
};

/** A call's outcome: its results by `Object.entries`, or its error by class, `name` and message. */
export function outcome(call: () => readonly object[]): unknown {
  try {
    return { results: call().map((r) => Object.entries(r)) };
  } catch (e) {
    const error = e as Error;
    return { error: [Object.getPrototypeOf(error), error.name, error.message] };
  }
}

/** Every word a document's surfaces make: each stem surface, alone and with each prefix and suffix. */
export function surfaceWords(db: MorphologyDb): string[] {
  const words = new Set<string>();
  for (const stem of db.stems.keys()) {
    words.add(stem);
    for (const prefix of db.prefixes.keys()) {
      for (const suffix of db.suffixes.keys()) {
        words.add(prefix + stem + suffix);
      }
    }
  }
  return [...words];
}

/** A part taken out of its Container: its Part_Meta and its Sections, in order, each a fresh array. */
export interface OpenPart {
  meta: unknown;
  sections: Map<string, SectionArray>;
}

/** An Asset taken apart: its Manifest and each part. */
export interface TakenApart {
  manifest: AssetManifest;
  parts: Record<PartKind, OpenPart>;
}

/** `asset` inflated and read back into its parts (no check beyond the Container reader's). */
export function takeApart(asset: AssetBytes): TakenApart {
  const manifest = parseManifest(asset.manifest);
  const parts = {} as Record<PartKind, OpenPart>;
  for (const shard of manifest.shards) {
    const decoded = readContainer(new Uint8Array(inflateSync(asset.shards[shard.path] as Uint8Array)), shard.part);
    parts[shard.part] = { meta: structuredClone(decoded.meta), sections: new Map(decoded.sections) };
  }
  return { manifest, parts };
}

/**
 * The Asset of `taken`: each part written into a Container (every Section
 * under the `none` Filter; the reader undoes whichever the Directory
 * names), deflated, and a Manifest with the new sizes and SHA-256s.
 */
export function putTogether(taken: TakenApart): AssetBytes {
  const shards: Record<string, Uint8Array> = {};
  const entries: ShardEntry[] = taken.manifest.shards.map((shard) => {
    const part = taken.parts[shard.part];
    const content = writeContainer(
      shard.part,
      part.meta,
      [...part.sections].map(([name, array]) => [name, array, 'none'] as const),
    );
    shards[shard.path] = new Uint8Array(deflateSync(content));
    return { ...shard, size: content.length, sha256: sha256Hex(content) };
  });
  return { manifest: writeManifest(taken.manifest, taken.manifest.counts, entries), shards };
}
