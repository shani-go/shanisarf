// Compiling is deterministic, and the Manifest names content only. For any
// `almorDoc` text: two compiles give the same Manifest and Shard_Content
// bytes; deflate levels 1 and 9 give the same Manifest (so the same
// Asset_Digest) while their Stored_Bytes may differ; and the Manifest is
// canonical, its Asset_Digest its SHA-256. Over the Database_Pin, compiling
// gives the committed `packages/shanisarf-db-msa/asset-digest.json`, run from
// src/ in process so it needs no build; that case skips with the replay notice
// when data/ lacks the pin.

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { inflateSync } from 'node:zlib';

import fc from 'fast-check';
import { describe, expect, it } from 'vitest';

import { compileDatabase } from '../../src/compile/compile-database.js';
import type { SourceRecord } from '../../src/compile/source-record.js';
import { parseManifest, serializeManifest } from '../../src/load/asset-manifest.js';
import { DB_PATH, databaseAvailable, SETUP_HINT } from '../parity/replay-support';

import { almorDoc } from './arbitraries';

const sha256 = (bytes: Uint8Array): string => createHash('sha256').update(bytes).digest('hex');

function recordFor(bytes: Uint8Array): SourceRecord {
  return {
    id: 'almor-doc',
    name: 'An almorDoc text',
    version: '0.0',
    source: 'https://example.invalid/almor-doc.db',
    sourceSha256: sha256(bytes),
    sourceBytes: bytes.length,
    license: { id: 'CC0-1.0', url: 'https://creativecommons.org/publicdomain/zero/1.0/' },
    credits: 'Generated by a property test.',
    disclaimer: 'No warranty.',
    citation: 'None.',
  };
}

const contents = (shards: Record<string, Uint8Array>): Record<string, Uint8Array> =>
  Object.fromEntries(Object.entries(shards).map(([path, stored]) => [path, new Uint8Array(inflateSync(stored))]));

describe('compiling is deterministic, and the Manifest names content only', () => {
  it('gives the same Manifest and Shard_Contents twice and at any level, canonically', async () => {
    await fc.assert(
      fc.asyncProperty(almorDoc.filter((text) => text.length > 0), async (text) => {
        const bytes = new TextEncoder().encode(text);
        const record = recordFor(bytes);
        const first = await compileDatabase(bytes, record);
        const second = await compileDatabase(bytes, record);
        expect(second.manifest).toEqual(first.manifest);
        expect(contents(second.shards)).toEqual(contents(first.shards));

        const fast = await compileDatabase(bytes, record, { level: 1 });
        expect(fast.manifest).toEqual(first.manifest);
        expect(fast.assetDigest).toBe(first.assetDigest);
        expect(contents(fast.shards)).toEqual(contents(first.shards));

        expect(serializeManifest(parseManifest(first.manifest))).toEqual(first.manifest);
        expect(first.assetDigest).toBe(sha256(first.manifest));
        const manifest = parseManifest(first.manifest);
        for (const shard of manifest.shards) {
          const content = contents(first.shards)[shard.path] as Uint8Array;
          expect(shard.size).toBe(content.length);
          expect(shard.sha256).toBe(sha256(content));
        }
      }),
      { numRuns: 100 },
    );
  });
});

if (!databaseAvailable()) {
  describe.skip('compiling is deterministic, over the pin', () => {
    it(`skipped: the Database_Pin is not present at ${DB_PATH} (run \`${SETUP_HINT}\`)`, () => {});
  });
} else {
  describe('compiling is deterministic, over the pin', () => {
    it('compiles to the committed asset-digest.json (compile:db --verify)', { timeout: 300_000 }, async () => {
      const pkgDir = new URL('../../packages/shanisarf-db-msa/', import.meta.url);
      const record = JSON.parse(readFileSync(new URL('source.json', pkgDir), 'utf8')) as SourceRecord;
      const expected = JSON.parse(readFileSync(new URL('asset-digest.json', pkgDir), 'utf8')) as unknown;
      const bytes = readFileSync(DB_PATH);
      const asset = await compileDatabase(new Uint8Array(bytes.buffer, bytes.byteOffset, bytes.byteLength), record);
      const manifest = parseManifest(asset.manifest);
      expect({
        formatVersion: manifest.formatVersion,
        assetDigest: asset.assetDigest,
        shards: manifest.shards.map(({ part, size, sha256: hash }) => ({ part, size, sha256: hash })),
      }).toEqual(expected);
    });
  });
}
